#!/usr/bin/env bash
set -euo pipefail

CACHE_CURRENT="$HOME/.cache/wallfx/current"
WAYBAR_CSS="$HOME/.config/waybar/colors.css"
KITTY_THEME="$HOME/.config/kitty/theme.conf"
OUT_FILE="$HOME/.config/hypr/hyprlock-theme.conf"

# Defaults (blue_lake.png palette)
BG="0f1116"
C0="1d1f26"
PRIMARY="3b62cc"
SECONDARY="6c54e0"
ACCENT="5d86f5"
ACCENT_SEC="775df5"
FG_TINT="bacbfa"
C15="f0f3fa"
FG_MUTED="939db8"
C1="eb6387"
C9="fa789b"
C2="6ce0ae"
C3="f0ad69"

valid_hex() {
    [[ "$1" =~ ^[0-9a-fA-F]{6}$ ]]
}

parse_css_hex() {
    local key="$1"
    local file="$2"
    [[ -r "$file" ]] || return 1
    awk -v k="$key" '
        $1 == "@define-color" && $2 == k {
            val = $3
            gsub(/[;#]/, "", val)
            print tolower(val)
            exit
        }
    ' "$file"
}

parse_kitty_hex() {
    local key="$1"
    local file="$2"
    [[ -r "$file" ]] || return 1
    awk -v k="$key" '
        $1 == k {
            val = $2
            gsub(/^#/, "", val)
            print tolower(val)
            exit
        }
    ' "$file"
}

hex_to_rgb_csv() {
    local h="$1"
    printf "%d, %d, %d" "0x${h:0:2}" "0x${h:2:2}" "0x${h:4:2}"
}

WALLPAPER="screenshot"
if [[ -r "$CACHE_CURRENT" ]]; then
    CANDIDATE=$(tr -d '\r\n' < "$CACHE_CURRENT")
    if [[ -n "$CANDIDATE" && -f "$CANDIDATE" ]]; then
        WALLPAPER="$CANDIDATE"
    fi
fi

v=$(parse_css_hex "primary" "$WAYBAR_CSS" || true)      && valid_hex "$v" && PRIMARY="$v"
v=$(parse_css_hex "secondary" "$WAYBAR_CSS" || true)    && valid_hex "$v" && SECONDARY="$v"
v=$(parse_css_hex "fg_tint" "$WAYBAR_CSS" || true)      && valid_hex "$v" && FG_TINT="$v"
v=$(parse_css_hex "fg_accent" "$WAYBAR_CSS" || true)    && valid_hex "$v" && ACCENT="$v"
v=$(parse_css_hex "fg_secondary" "$WAYBAR_CSS" || true) && valid_hex "$v" && ACCENT_SEC="$v"
v=$(parse_css_hex "fg_muted" "$WAYBAR_CSS" || true)     && valid_hex "$v" && FG_MUTED="$v"

v=$(parse_kitty_hex "background" "$KITTY_THEME" || true) && valid_hex "$v" && BG="$v"
v=$(parse_kitty_hex "color0" "$KITTY_THEME" || true)     && valid_hex "$v" && C0="$v"
v=$(parse_kitty_hex "color1" "$KITTY_THEME" || true)     && valid_hex "$v" && C1="$v"
v=$(parse_kitty_hex "color2" "$KITTY_THEME" || true)     && valid_hex "$v" && C2="$v"
v=$(parse_kitty_hex "color3" "$KITTY_THEME" || true)     && valid_hex "$v" && C3="$v"
v=$(parse_kitty_hex "color9" "$KITTY_THEME" || true)     && valid_hex "$v" && C9="$v"
v=$(parse_kitty_hex "color15" "$KITTY_THEME" || true)    && valid_hex "$v" && C15="$v"

BG_CSV=$(hex_to_rgb_csv "$BG")
C0_CSV=$(hex_to_rgb_csv "$C0")
P_CSV=$(hex_to_rgb_csv "$PRIMARY")

TMP_OUT="${OUT_FILE}.tmp.$$"
cat > "$TMP_OUT" <<EOF
# Auto-generated by sync-lock-theme.sh from wallfx palette
\$wallpaper = $WALLPAPER
\$bg = rgb($BG)
\$bg_glass = rgba($BG_CSV, 0.76)
\$bg_surface = rgba($C0_CSV, 0.72)
\$fg = rgb($FG_TINT)
\$fg_bright = rgb($C15)
\$fg_muted = rgb($FG_MUTED)
\$primary = rgb($PRIMARY)
\$secondary = rgb($SECONDARY)
\$accent = rgb($ACCENT)
\$accent_sec = rgb($ACCENT_SEC)
\$border_active = rgba(${PRIMARY}ee) rgba(${SECONDARY}ee) 45deg
\$border_subtle = rgba($P_CSV, 0.42)
\$check_ring = rgba(${ACCENT}ee) rgba(${C2}ee) 120deg
\$error_ring = rgba(${C1}ee) rgba(${C9}ee) 45deg
\$warn = rgb($C3)
\$placeholder = <span foreground="##${FG_MUTED}"><i>Введите пароль...</i></span>
\$fail_msg = <span foreground="##${C1}"><i>Неверный пароль (\$ATTEMPTS)</i></span>
EOF

mv -f "$TMP_OUT" "$OUT_FILE"
